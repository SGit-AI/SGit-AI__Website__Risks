#!/usr/bin/env python3
"""Generates llms-full.txt — the whole site in one fetch.

Run from anywhere: python3 admin/build/gen_llms_full.py

Why this file exists, and why it is not optional here. An agent consuming the parent
site reported that the index fetch worked and then LINK-FOLLOWING FAILED, because agent
fetch tools refuse URLs a search has not already returned. Its conclusion was that
llms.txt "is not a convenience for such agents but the whole surface". The second
mitigation it recommended, after making each llms.txt entry carry a fact rather than a
topic, is a single-file concatenation of everything so that one fetch gets the lot.
The commissioned audience for THIS site is agents, so that mitigation is a deliverable.

Concatenates, in order: llms.txt · the front page's markdown twin · the prose of every
rendered page, in nav order · the twelve source documents of the brief pack, verbatim.

No third-party dependency: the HTML→text step is deliberately small and regex-based, so
this runs anywhere Python does. It is lossy on purpose — chrome, scripts and styling are
dropped, prose, headings, tables and list items are kept.
"""
import html
import re
from pathlib import Path

ROOT    = Path(__file__).resolve().parents[2]
VERSION = (ROOT / "admin/build/version.txt").read_text().strip()

# Page order = the teaching order the site argues in, which is also chrome.py's NAV order.
PAGES = [
    "index.html",
    "acceptance/index.html",
    "acceptance/underwriting.html",
    "acceptance/no-deny.html",
    "acceptance/the-ladder.html",
    "acceptance/unaccepted-is-critical.html",
    "acceptance/workflow.html",
    "acceptable/index.html",
    "acceptable/appetite.html",
    "ladder/index.html",
    "ladder/formulas.html",
    "ladder/bridges.html",
    "ladder/absence.html",
    "register/index.html",
    "blast-radius/index.html",
    "plug/index.html",
    "plug/recoverability.html",
    "practice/index.html",
    "ramm/index.html",
    "examples/index.html",
    "examples/2fa.html",
    "examples/browser-isolation.html",
    "examples/article-26-5.html",
    "examples/vaults.html",
    "examples/scenarios.html",
    "examples/plug-register.html",
    "concepts/index.html",
    "agents/index.html",
    "shipped/index.html",
    "origins/index.html",
    "network/index.html",
    "documents/index.html",
    "about/participant.html",
    "admin/index.html",
    "admin/comms.html",
    "admin/versions.html",
]

BRIEFS = [
    "README.md",
    "00__BRIEF.md",
    "01__concepts-index.md",
    "02__risk-acceptance.md",
    "03__worked-examples-and-vaults.md",
    "04__riskmandate-refactor.md",
    "05__site-architecture.md",
    "06__boundaries-and-house-style.md",
    "07__gaps-and-open-questions.md",
    "08__source-manifest.csv",
    "PUBLIC.md",
    "LICENSE.md",
]

HEADER = f"""# risks.sgit.ai — everything, in one file

Site version: {VERSION}. Generated by admin/build/gen_llms_full.py — do not edit by hand.

This is /llms.txt, then the front page, then the prose of every page on the site in
teaching order, then the twelve source documents of the brief pack, concatenated. It
exists because agent fetch tools frequently refuse URLs a search has not already
returned, which makes link-following unreliable and makes a single-file surface the
practical one. If you can make more than one request, prefer:

  · https://risks.sgit.ai/data/concepts.json   — the 42 concepts as structured data
  · https://risks.sgit.ai/briefs/<filename>    — the source documents, verbatim
  · https://risks.sgit.ai/llms.txt             — the annotated map

READ THIS FIRST. Essentially none of the risk model described below is implemented in
code. Greps for risk_, RiskAcceptance, risk_register and riskmandate across the
implementing repository return zero matches. This is a research site: the concepts are
argued, the worked examples are real graphs, four vaults are live and browsable, and
the engine is not built. Do not describe any of it as an existing feature.

All content is released under the Creative Commons Attribution 4.0 International licence
(CC BY 4.0). Third-party material quoted inside these documents stays under its own terms.

"""

SEP = "\n\n" + "=" * 78 + "\n== {name}\n" + "=" * 78 + "\n\n"


def to_text(src):
    """HTML -> plain text. Small, regex-based and deliberately lossy."""
    t = src
    for block in ("head", "script", "style", "nav", "footer"):
        t = re.sub(rf"<{block}\b.*?</{block}>", "", t, flags=re.S | re.I)
    t = re.sub(r"<!--.*?-->", "", t, flags=re.S)
    t = re.sub(r'<div class="crumb">.*?</div>', "", t, flags=re.S)
    t = re.sub(r'<div class="pagenav">.*?</div>', "", t, flags=re.S)
    t = re.sub(r"<h1\b[^>]*>(.*?)</h1>", r"\n\n# \1\n", t, flags=re.S | re.I)
    t = re.sub(r"<h2\b[^>]*>(.*?)</h2>", r"\n\n## \1\n", t, flags=re.S | re.I)
    t = re.sub(r"<h3\b[^>]*>(.*?)</h3>", r"\n\n### \1\n", t, flags=re.S | re.I)
    t = re.sub(r"<h4\b[^>]*>(.*?)</h4>", r"\n\n#### \1\n", t, flags=re.S | re.I)
    t = re.sub(r"<li\b[^>]*>", "\n  - ", t, flags=re.I)
    t = re.sub(r"</(p|tr|div|pre|blockquote|ul|ol|table)>", "\n", t, flags=re.I)
    t = re.sub(r"</t[hd]>", " | ", t, flags=re.I)
    t = re.sub(r"<br\s*/?>", "\n", t, flags=re.I)
    t = re.sub(r"<[^>]+>", "", t)
    t = html.unescape(t)
    t = re.sub(r"[ \t]+", " ", t)
    t = re.sub(r" *\n *", "\n", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def main():
    parts = [HEADER, SEP.format(name="llms.txt"), (ROOT / "llms.txt").read_text()]
    parts.append(SEP.format(name="index.md — the front page as markdown"))
    parts.append((ROOT / "index.md").read_text())

    missing = []
    for rel in PAGES:
        p = ROOT / rel
        if not p.exists():
            missing.append(rel)
            continue
        parts.append(SEP.format(name=f"/{rel}"))
        parts.append(to_text(p.read_text()))

    for name in BRIEFS:
        p = ROOT / "briefs" / name
        if not p.exists():
            missing.append(f"briefs/{name}")
            continue
        parts.append(SEP.format(name=f"briefs/{name} — source document, verbatim"))
        parts.append(p.read_text())

    out = "\n".join(parts).rstrip() + "\n"
    (ROOT / "llms-full.txt").write_text(out)
    words = len(out.split())
    print(f"gen_llms_full: {len(out):,} bytes, ~{words:,} words, "
          f"{len(PAGES) - len([m for m in missing if m in PAGES])} page(s) + "
          f"{len(BRIEFS)} document(s)")
    for m in missing:
        print(f"  ! missing: {m}")


if __name__ == "__main__":
    main()
